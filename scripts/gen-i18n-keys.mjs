// Generates src/i18n/keys.gen.ts from locales/en.ftl so every t() call is
// type-checked: a typo or a removed key fails `tsc`.
// Usage: node scripts/gen-i18n-keys.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "@fluent/syntax";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "locales/en.ftl"), "utf8");
const resource = parse(src, { withSpans: false });

const errors = resource.body.filter((e) => e.type === "Junk");
if (errors.length) {
  console.error("en.ftl has syntax errors:\n" + errors.map((j) => j.content).join("\n"));
  process.exit(1);
}

function collectVars(node, out) {
  if (!node || typeof node !== "object") return;
  if (node.type === "VariableReference") out.add(node.id.name);
  for (const v of Object.values(node)) {
    if (Array.isArray(v)) v.forEach((x) => collectVars(x, out));
    else if (v && typeof v === "object") collectVars(v, out);
  }
}

const entries = resource.body
  .filter((e) => e.type === "Message")
  .map((m) => {
    const vars = new Set();
    collectVars(m.value, vars);
    return { id: m.id.name, vars: [...vars].sort() };
  });

const lines = [
  "// AUTO-GENERATED by scripts/gen-i18n-keys.mjs from locales/en.ftl. Do not edit.",
  "",
  "export interface MessageArgs {",
  ...entries.map(({ id, vars }) =>
    `  ${JSON.stringify(id)}: ${vars.length ? `{ ${vars.map((v) => `${v}: string | number`).join("; ")} }` : "undefined"};`,
  ),
  "}",
  "",
  "export type MessageKey = keyof MessageArgs;",
  "",
  `export const MESSAGE_KEYS: readonly MessageKey[] = ${JSON.stringify(entries.map((e) => e.id), null, 2)};`,
  "",
];
const out = lines.join("\n");
const target = join(root, "src/i18n/keys.gen.ts");

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error("src/i18n/keys.gen.ts is out of date. Run `npm run i18n:gen`.");
    process.exit(1);
  }
  console.log(`i18n keys up to date (${entries.length} keys).`);
} else {
  writeFileSync(target, out);
  console.log(`Generated ${entries.length} typed i18n keys.`);
}
