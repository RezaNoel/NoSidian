fn main() {
    // Rebuild the Windows resource (exe icon) whenever the icons change, even
    // with a warm CI cache.
    println!("cargo:rerun-if-changed=icons");
    println!("cargo:rerun-if-changed=tauri.conf.json");
    // The Google client is compiled in from the build environment.
    println!("cargo:rerun-if-env-changed=GOOGLE_CLIENT_ID");
    println!("cargo:rerun-if-env-changed=GOOGLE_CLIENT_SECRET");
    // The share sheet plugin is an Android-only dependency, so its permission
    // may only be granted when building for Android.
    let mobile = std::path::Path::new("capabilities/mobile.json");
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("android") {
        let _ = std::fs::write(
            mobile,
            r#"{
  "identifier": "mobile",
  "description": "Generated by build.rs: Android-only permissions",
  "windows": ["main"],
  "permissions": ["sharekit:default"]
}
"#,
        );
    } else {
        let _ = std::fs::remove_file(mobile);
    }
    tauri_build::build()
}
